#  determine if a fruit is ripe:overipe or unripe based on it colours (eg banana:green_unripe<yellow_ripe<brown-overipe)




fruits=("green")


if fruits == "green":
    print("unripe")

elif fruits == "yellow":
    print("ripe")

elif fruits == "brown":
    print("overipe")

else:
    print("invalid")
