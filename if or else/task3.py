# Grade calculation

# assign a letter grade on a students score A(90-100), B(80-89), c(70-79), d(60-69), f(below 60)

grade=60

if grade >=90:
    print("A")

elif grade >=80:
    print("B")

elif grade >=70:
    print("C")

elif grade >60:
    print("D") 

else:
    print("below")   
